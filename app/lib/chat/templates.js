// type -> template key for the "why" line of a question chip row
export const QUESTION_KEY = {
  budget: "ask_budget", occasion: "ask_occasion", category: "ask_category",
  brand: "ask_brand", for_whom: "ask_for_whom", size: "ask_size", capacity: "ask_capacity",
  recipient: "gift_recipient",
};

export function T_(lang, key, vars = {}) {
  let t = (T[lang] && T[lang][key]) || T.en[key] || "";
  for (const [k, v] of Object.entries(vars)) t = t.split("{" + k + "}").join(String(v));
  return t;
}
